#!/usr/bin/env node
/* WCAG contrast audit of every UI text/background pair in the Kalamkari tokens (Sprint 2, task 6).
   Writes docs/sprint2/contrast.md. Exit 1 if any pair fails its WCAG 2.2 AA threshold.
   AA: 4.5:1 for normal text, 3:1 for large text (≥24px, or ≥18.66px bold) and for UI component boundaries. */
import fs from "node:fs";

const hex = h => [1, 3, 5].map(i => parseInt(h.slice(i, i + 2), 16) / 255);
const lin = c => (c <= 0.04045 ? c / 12.92 : ((c + 0.055) / 1.055) ** 2.4);
const L = h => { const [r, g, b] = hex(h).map(lin); return 0.2126 * r + 0.7152 * g + 0.0722 * b; };
const ratio = (a, b) => { const [x, y] = [L(a), L(b)].sort((p, q) => q - p); return (x + 0.05) / (y + 0.05); };

const T = {
  cotton: "#f6ecd8", cottonDeep: "#eedfc0", caption: "#fbf4e4", chip: "#f1e3c4",
  ink: "#2b2018", madder: "#a63a2b", madderBrown: "#8a2f22", indigo: "#2e4377", leaf: "#5b7a46", muted: "#6e5b45", white: "#fbf4e4",
};

/* [where it appears, foreground, background, size class] */
const PAIRS = [
  ["Body text on cotton", "ink", "cotton", "normal"],
  ["Body text on caption cream", "ink", "caption", "normal"],
  ["Headings (Rozha One) on cotton", "madderBrown", "cotton", "large"],
  ["Caption title on caption cream", "madderBrown", "caption", "large"],
  ["Parva line / Devanagari / jump links on cotton", "madder", "cotton", "normal"],
  ["Jump links on caption cream", "madder", "caption", "normal"],
  ["Choice label ('Follow …') on caption cream", "madder", "caption", "normal"],
  ["Muted text (scroll hint, meta) on cotton", "muted", "cotton", "normal"],
  ["Muted text on caption cream", "muted", "caption", "normal"],
  ["Muted text on chip", "muted", "chip", "normal"],
  ["Map tab gloss (11px) on chip (active tab)", "muted", "chip", "normal"],
  ["'Who is speaking' chip: indigo on chip", "indigo", "chip", "normal"],
  ["'✓ walked' tick: leaf on caption cream", "leaf", "caption", "normal"],
  ["Primary button: cotton on madder", "cotton", "madder", "normal"],
  ["Return button: caption cream on madder", "white", "madder", "normal"],
  ["Toast: cotton on madder", "cotton", "madder", "normal"],
  ["Coach mark: caption cream on indigo", "white", "indigo", "normal"],
  ["Text on cotton-deep (stage background)", "ink", "cottonDeep", "normal"],
  ["Muted on cotton-deep", "muted", "cottonDeep", "normal"],
  ["Ink borders / focus ring vs cotton (UI component)", "ink", "cotton", "ui"],
  ["Indigo focus outline vs cotton (UI component)", "indigo", "cotton", "ui"],
];

const need = { normal: 4.5, large: 3, ui: 3 };
let fails = 0;
const rows = PAIRS.map(([where, fg, bg, size]) => {
  const r = ratio(T[fg], T[bg]); const ok = r >= need[size]; if (!ok) fails++;
  return `| ${where} | \`${T[fg]}\` on \`${T[bg]}\` | ${size} | ${r.toFixed(2)}:1 | ${need[size]}:1 | ${ok ? "✅ pass" : "❌ FAIL"} |`;
});
const md = `# Contrast audit — Kalamkari tokens (WCAG 2.2 AA)

Generated by \`node scripts/contrast.mjs\`. AA thresholds: 4.5:1 normal text; 3:1 large text (≥24px or ≥18.66px bold) and UI components.
Painted scenes are art and get text alternatives instead (Sprint 2, D4).

| Where | Colours | Size | Ratio | Needs | Result |
|---|---|---|---|---|---|
${rows.join("\n")}

**${PAIRS.length - fails}/${PAIRS.length} pairs pass.**
`;
fs.mkdirSync("docs/sprint2", { recursive: true });
fs.writeFileSync("docs/sprint2/contrast.md", md);
console.log(md);
process.exit(fails ? 1 : 0);
